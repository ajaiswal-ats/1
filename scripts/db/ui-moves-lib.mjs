/* Cleanup SQL for a manual UI stage-change test run, from the development test-run record written by the Vite dev server
   (scripts/dev/move-record-lib.mjs). It uses the run's exact idempotency keys, including requests that got no answer, and
   the same refusal rules as the API test runs (api-moves-lib.mjs restoreSql): any portal move or key in the fictional
   clients that is not one of the recorded keys, including later moves on the same candidates, makes it refuse.
   The baseline of each submission is the version and stage the user saw before the run's first request on it. */
import { TARGETS, restoreSql, targetId } from "./api-moves-lib.mjs";

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const refOf = (id) => Object.keys(TARGETS).find((ref) => targetId(ref) === id);

/** Converts a UI run record into the restore record format, or throws if it is malformed or touches an unknown submission. */
export function uiRunToRecord(run) {
  if (run?.kind !== "ui-moves" || !UUID.test(run.runId || "") || !Array.isArray(run.entries)) throw new Error("not a UI move run record");
  const sent = run.entries.filter((e) => e.phase === "sent");
  const outcome = new Map(run.entries.filter((e) => e.phase === "outcome").map((e) => [`${e.key}:${e.submission_id}`, e.outcome]));
  const baseline = {}, requests = [];
  for (const e of sent) {
    const ref = refOf(e.submission_id);
    if (!ref) throw new Error(`run record has a request for a submission that is not a fictional test submission (${e.submission_id})`);
    const b = baseline[ref];
    if (!b || e.expected_version < b.version) baseline[ref] = { submission_id: e.submission_id, client: TARGETS[ref].client, stage: e.seen_stage, version: e.expected_version, updated_at: null, source: "ui" };
    else if (e.expected_version === b.version && e.seen_stage !== b.stage) throw new Error(`run record shows ${ref} at version ${b.version} as both ${b.stage} and ${e.seen_stage}`);
    const o = outcome.get(`${e.key}:${e.submission_id}`);
    requests.push({ step: `UI${requests.length + 1}`, ref, submission_id: e.submission_id, key: e.key, to_stage: e.to_stage, expected_version: e.expected_version,
      state: o === undefined || o === "uncertain" ? "unknown" : "answered", status: o === "ok" ? 200 : o?.startsWith("error:") ? 400 : undefined });
  }
  return { runId: run.runId, project: run.project, createdAt: run.createdAt, keys: {}, baseline, requests };
}

export function uiRestoreSql(run) {
  const record = uiRunToRecord(run), keys = new Set(record.requests.map((r) => r.key));
  const header = `-- GENERATED by scripts/db/ui-moves-restore.mjs from the development test-run record of manual UI run ${record.runId}
-- (project ${record.project}, started ${record.createdAt}). Restores the fictional baseline after that run, and nothing else.
-- Review before running; run it yourself in the SQL Editor.
--
-- The run sent ${record.requests.length} request(s) with ${keys.size} idempotency key(s) on: ${Object.keys(record.baseline).join(", ") || "nothing"}.
-- Requests without an answer are included: the key lookup decides whether they were saved.
-- What it can change, and only if every check passes:
-- * app_private.idempotency_keys: deletes the rows of this run's recorded keys (matched by key and submission).
-- * public.submission_events: deletes only the events those key rows point to (portal moves by a test member).
-- * public.submissions: puts those submissions back to the version and stage the user saw before the run's first request.
--   Their updated_at keeps the time of the test.
-- Never touched: seed events, memberships, users, roles, people, other submissions, or anything in Auth.
--
-- It refuses, and changes nothing, if any portal move or key in the fictional clients is not one of this run's keys
-- (including later moves on the same candidates), a key does not match its event, a submission's history after the
-- baseline is not this run's, its history up to the baseline differs, or its stage/version does not match its history.
-- Safe to run again. One DO statement (atomic), then a read-only check, which is what the editor shows.`;
  return restoreSql(record, { header });
}
