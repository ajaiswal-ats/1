/* Writes supabase/seed/m6_fictional.sql and m6_remove_fictional.sql: client-safe screening summaries for the two
   fictional clients, from the frontend's fictional dataset (src/data/fixtures.ts: each submission's screening call).

   Milestone 3 freezes published packages, and every target package on the database is already published. Screening
   content may only be added while a package is a draft, so the seed does not touch the published versions. For each
   target it adds a NEW draft version of the package, copies the published version's reviewed content and evidence into it
   exactly (read from the database, not from this file), adds the screening summary while it is a draft, and publishes it
   with milestone 3's owner-only publish_package. That supersedes the old version (a permitted state change; its content
   is unchanged and stays frozen). No milestone 3 guard is relaxed and no published content is edited.

   Removal (m6_remove_fictional.sql) deletes only the screening summaries, with milestone 3's explicit fictional cleanup.
   The new package versions stay published with the same content as before (milestone 3 content; superseded versions
   cannot be re-published). To restore milestone 3's seeded rows exactly, run m3_remove_fictional.sql and then
   m3_fictional.sql. Usage: node scripts/db/gen-seed-m6.mjs */
import fs from "node:fs";
import path from "node:path";
import { FIXTURE } from "../../src/data/fixtures.ts";
import { ROOT } from "./env.mjs";

const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const id = (s) => `md5(${q(s)})::uuid`;
const client = (c) => id(`portal-m1:client:${c}`);
const fictional = `(${client("harbor")}, ${client("northwind")})`;

const targets = FIXTURE.subs.filter((s) => s.iv).map((s) => {
  const v = s.iv;
  if (v.date > s.shared) throw new Error(`${s.id}: call after the shared date`);
  v.moments.forEach(([m], i) => { if (!Number.isInteger(m) || m < 0 || m >= v.dur || (i && m <= v.moments[i - 1][0])) throw new Error(`${s.id}: key moment outside the call or out of order`); });
  return { ref: s.id, old: `portal-m3:package:harbor:${s.id}:1`, pkg: `portal-m6:package:harbor:${s.id}`, scr: `portal-m6:screening:harbor:${s.id}`, sub: `portal-m1:submission:harbor:${s.id}`,
    call: v.date, dur: v.dur, by: v.by, summary: v.summary, notes: v.notes, moments: v.moments.map(([minute, label]) => ({ minute, label })), reqs: s.req.length };
});

const steps = targets.map((t) => `-- ${t.ref}: new draft version with the published version's content and evidence, the summary, then publish.
insert into public.submission_packages (id, client_id, submission_id, role_id, requirement_set_id, version, why_shared, strengths, points_to_clarify, key_facts)
  select ${id(t.pkg)}, p.client_id, p.submission_id, p.role_id, p.requirement_set_id,
         (select max(x.version) + 1 from public.submission_packages x where x.submission_id = p.submission_id), p.why_shared, p.strengths, p.points_to_clarify, p.key_facts
  from public.submission_packages p where p.id = ${id(t.old)};
insert into public.requirement_evidence (id, client_id, package_id, requirement_set_id, requirement_id, status, evidence, source_label)
  select md5('${t.pkg}:evidence:' || e.requirement_id)::uuid, e.client_id, ${id(t.pkg)}, e.requirement_set_id, e.requirement_id, e.status, e.evidence, e.source_label
  from public.requirement_evidence e where e.package_id = ${id(t.old)};
insert into public.screening_summaries (id, client_id, package_id, requirement_set_id, call_on, duration_minutes, recruiter_name, summary, notes_for_client, key_moments)
  select ${id(t.scr)}, p.client_id, p.id, p.requirement_set_id, ${q(t.call)}, ${t.dur}, ${q(t.by)}, ${q(t.summary)}, ${q(t.notes)}, ${q(JSON.stringify(t.moments))}::jsonb
  from public.submission_packages p where p.id = ${id(t.pkg)};
select app_private.publish_package(${id(t.pkg)});`).join("\n");

const evidenceCopies = targets.reduce((n, t) => n + t.reqs, 0);
const counts = { screening: targets.length, packages: 17 + targets.length, evidence: 67 + evidenceCopies,
  packageStates: { published: 14, draft: 1, paused: 1, withdrawn: 1, superseded: targets.length },
  harborVisible: { packages: 11, evidence: 48, screening: targets.length }, northwindVisible: { packages: 0, evidence: 0, screening: 0 } };
const header = (what) => `-- GENERATED by scripts/db/gen-seed-m6.mjs from src/data/fixtures.ts. Do not edit by hand. Fictional data only.\n-- ${what}\n`;

const seed = `begin;
do $$
begin
  if to_regclass('public.screening_summaries') is null then raise exception 'milestone 6 migration not found: nothing inserted'; end if;
  if (select count(*) from public.submissions where client_id in ${fictional}) <> 15 then raise exception 'the milestone 1 fictional seed is not as expected: nothing inserted'; end if;
  if exists (select 1 from public.screening_summaries) then raise exception 'screening summaries already exist: nothing inserted (remove them first with m6_remove_fictional.sql)'; end if;
  -- Each target's published package must be milestone 3's seeded version 1, with no milestone 6 version yet.
  if (select count(*) from public.submission_packages p
      where p.id in (${targets.map((t) => id(t.old)).join(", ")}) and p.state = 'published') <> ${targets.length}
     or exists (select 1 from public.submission_packages p
                where p.state = 'published' and p.submission_id in (${targets.map((t) => id(t.sub)).join(", ")})
                  and p.id not in (${targets.map((t) => id(t.old)).join(", ")}))
     or exists (select 1 from public.submission_packages where id in (${targets.map((t) => id(t.pkg)).join(", ")})) then
    raise exception 'the milestone 3 packages are not as seeded: nothing inserted';
  end if;
end $$;
${steps}
commit;
`;
const remove = `begin;
do $$
begin
  if to_regclass('public.screening_summaries') is null then raise exception 'milestone 6 not found: nothing changed'; end if;
end $$;
-- Milestone 3's explicit fictional cleanup (table owner, fictional clients only, this transaction only): the summaries
-- are frozen with their published packages.
select set_config('app.m3_fictional_cleanup', 'on', true);
delete from public.screening_summaries where client_id in ${fictional};
select set_config('app.m3_fictional_cleanup', '', true);
commit;
`;
fs.writeFileSync(path.join(ROOT, "supabase/seed/m6_fictional.sql"), header(`Milestone 6 seed: ${targets.length} client-safe screening summaries (Harbor), each on a new package version. One transaction.
-- It stops without changing anything unless milestone 6 is applied, the milestone 1 fictional seed is present, no
-- summaries exist yet, and each target's published package is still milestone 3's seeded version 1.
-- How it treats the published packages: see scripts/db/gen-seed-m6.mjs (new draft version, exact copy, summary, publish;
-- the old version is superseded with its content unchanged). After this seed, checks/m3_post_seed.sql no longer matches
-- (it describes milestone 3's seed alone: 9 more package versions); use checks/m6_post_seed.sql.
-- Expected: ${JSON.stringify(counts)}.`) + seed);
fs.writeFileSync(path.join(ROOT, "supabase/seed/m6_remove_fictional.sql"), header(`Removes ALL screening summaries of the two fictional clients. One transaction. Run it before rolling milestone 6 back.
-- The package versions the milestone 6 seed published stay (milestone 3 content, unchanged). To restore milestone 3's
-- seeded rows exactly, run m3_remove_fictional.sql and then m3_fictional.sql afterwards.`) + remove);
fs.writeFileSync(path.join(ROOT, "supabase/seed/m6_counts.json"), JSON.stringify(counts, null, 2) + "\n");
console.log(`wrote supabase/seed/m6_fictional.sql, m6_remove_fictional.sql, m6_counts.json: ${JSON.stringify(counts)}`);
