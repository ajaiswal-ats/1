/* Writes supabase/seed/m1_fictional.sql from the frontend's fictional dataset (src/data/fixtures.ts), plus a second
   fictional client and one unpublished submission per client for the access tests. Deterministic ids (md5 of a label),
   so re-running the seed resets the same rows. Fictional data only.
   Usage: npm run db:seed:generate */
import fs from "node:fs";
import path from "node:path";
import { FIXTURE } from "../../src/data/fixtures.ts";
import { ROOT } from "./env.mjs";

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const id = (...parts) => `md5(${q(["portal-m1", ...parts].join(":"))})::uuid`;

const HARBOR = { ref: "harbor", name: "Harbor Industrial Supply" };
const NORTHWIND = { ref: "northwind", name: "Northwind Fictional Co." };
const roles = FIXTURE.roles.map((r) => ({ client: HARBOR.ref, ref: r.id, title: r.title, location: r.loc, status: r.status, opened: r.opened, recruiter: r.contact }));
roles.push({ client: NORTHWIND.ref, ref: "ops", title: "Operations Coordinator", location: "Remote · US", status: "Open", opened: "2026-10-01", recruiter: "Jamie Scott" });

const people = [...new Map(FIXTURE.subs.map((s) => [s.pid, { client: HARBOR.ref, ref: s.pid, name: s.name, headline: s.head, location: s.loc }])).values()];
people.push({ client: HARBOR.ref, ref: "zz", name: "Unpublished Test Candidate", headline: "Fictional · unpublished submission", location: "Chicago, IL" });
people.push({ client: NORTHWIND.ref, ref: "n1", name: "Robin Hale", headline: "Operations Analyst · Fictional Co.", location: "Denver, CO" });
people.push({ client: NORTHWIND.ref, ref: "n2", name: "Casey Lund", headline: "Logistics Planner · Fictional Co.", location: "Austin, TX" });

const subs = FIXTURE.subs.map((s) => ({ client: HARBOR.ref, ref: s.id, role: s.role, person: s.pid, stage: s.stage, shared: s.shared, publication: "published" }));
subs.push({ client: HARBOR.ref, ref: "zz-isl", role: "isl", person: "zz", stage: "To review", shared: "2026-10-11", publication: "unpublished" });
subs.push({ client: NORTHWIND.ref, ref: "n1-ops", role: "ops", person: "n1", stage: "To review", shared: "2026-10-08", publication: "published" });
subs.push({ client: NORTHWIND.ref, ref: "n2-ops", role: "ops", person: "n2", stage: "To review", shared: "2026-10-10", publication: "unpublished" });

/* Events: "shared" (version 1), then each fixture move in date order. The final stage must match the submission. */
const events = [];
for (const s of subs) {
  events.push({ s, v: 1, kind: "shared", to: "To review", on: s.shared, actor: "revenue_optics" });
  const moves = FIXTURE.moves.filter((m) => m.sid === s.ref).sort((a, b) => (a.d < b.d ? -1 : a.d > b.d ? 1 : 0));
  moves.forEach((m, i) => events.push({ s, v: i + 2, kind: "stage_move", to: m.to, on: m.d, actor: m.by === "you" ? "client" : "revenue_optics" }));
  const last = events.filter((e) => e.s === s).at(-1);
  if (last.to !== s.stage) throw new Error(`${s.ref}: stage ${s.stage} does not match its last move (${last.to})`);
  s.version = last.v;
}

const clientIds = `(${id("client", HARBOR.ref)}, ${id("client", NORTHWIND.ref)})`;
const sql = `-- GENERATED by scripts/db/gen-seed.mjs from src/data/fixtures.ts. Do not edit by hand. Fictional data only.
-- Resets the seeded clients' roles, people, submissions and events (memberships and test users are kept).
begin;
insert into public.clients (id, ref, name) values
  ${[HARBOR, NORTHWIND].map((c) => `(${id("client", c.ref)}, ${q(c.ref)}, ${q(c.name)})`).join(",\n  ")}
on conflict (ref) do update set name = excluded.name;

delete from public.roles where client_id in ${clientIds};
delete from public.people where client_id in ${clientIds};

insert into public.roles (id, client_id, ref, title, location, status, opened_on, recruiter_name) values
  ${roles.map((r) => `(${id("role", r.client, r.ref)}, ${id("client", r.client)}, ${q(r.ref)}, ${q(r.title)}, ${q(r.location)}, ${q(r.status)}, ${q(r.opened)}, ${q(r.recruiter)})`).join(",\n  ")};

insert into public.people (id, client_id, ref, name, headline, location) values
  ${people.map((p) => `(${id("person", p.client, p.ref)}, ${id("client", p.client)}, ${q(p.ref)}, ${q(p.name)}, ${q(p.headline)}, ${q(p.location)})`).join(",\n  ")};

insert into public.submissions (id, client_id, ref, role_id, person_id, stage, shared_on, publication, version) values
  ${subs.map((s) => `(${id("submission", s.client, s.ref)}, ${id("client", s.client)}, ${q(s.ref)}, ${id("role", s.client, s.role)}, ${id("person", s.client, s.person)}, ${q(s.stage)}, ${q(s.shared)}, ${q(s.publication)}, ${s.version})`).join(",\n  ")};

insert into public.submission_events (client_id, submission_id, submission_version, kind, to_stage, occurred_on, actor_kind, source) values
  ${events.map((e) => `(${id("client", e.s.client)}, ${id("submission", e.s.client, e.s.ref)}, ${e.v}, ${q(e.kind)}, ${q(e.to)}, ${q(e.on)}, ${q(e.actor)}, 'seed')`).join(",\n  ")};
commit;
`;
const out = path.join(ROOT, "supabase/seed/m1_fictional.sql");
fs.writeFileSync(out, sql);
console.log(`wrote ${path.relative(ROOT, out)}: ${roles.length} roles, ${people.length} people, ${subs.length} submissions (${subs.filter((s) => s.publication === "unpublished").length} unpublished), ${events.length} events`);
